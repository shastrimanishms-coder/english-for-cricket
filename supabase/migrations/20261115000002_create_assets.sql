-- ============================================================================
-- 20261115000002_create_assets.sql
-- Creates public.assets (table) + RLS policies.
--
-- WHY: Backend verification (2026-11-15) found this table missing
-- (PostgREST PGRST205) while every other table the code references exists.
--
-- WHAT THE CODE ACTUALLY DOES TODAY (read before judging this schema):
--   * src/components/admin/SystemSettings.tsx uploads the site logo to the
--     STORAGE bucket named 'assets' (which already exists) and stores the
--     resulting public URL in site_settings under the key 'site_logo_url'.
--     NO code in the repo reads or writes an assets TABLE yet.
--   * This table is therefore a registry of uploaded site assets (today:
--     logos), mirroring the bucket the same way 20261115000001 mirrors the
--     lesson_media bucket. Creating it closes the verified missing-object
--     gap and changes nothing in the app's current behaviour.
--   * Column choices are inferred from SystemSettings.tsx and from the
--     conventions of the sibling tables (downloads / videos / games).
--     Every inference is marked "-- inferred".
--
-- Depends on public.is_admin() from 20261115000001_create_lesson_media.sql
-- (run that file first, or 20261115000004 which also creates it).
-- ============================================================================

create table if not exists public.assets (
  id          uuid primary key default gen_random_uuid(),
  -- Original file name as picked (DocumentPicker asset.name). -- inferred
  name        text,
  -- Storage object name inside the 'assets' bucket, generated by
  -- SystemSettings.uploadLogo() as: logo_<ts>.<ext>
  file_name   text not null,
  -- Public URL returned by storage getPublicUrl(); the same value the code
  -- stores in site_settings.site_logo_url for the logo.
  file_url    text not null,
  -- What the asset is used for. Today the only uploader is the site logo;
  -- the picker in SystemSettings only accepts images ('image/*').
  asset_type  text not null default 'logo'
              check (asset_type in ('logo', 'image', 'other')),
  -- file.mimeType as reported by expo-document-picker (native uploads). -- inferred
  mime_type   text,
  uploaded_by uuid references auth.users (id) on delete set null,
  created_at  timestamptz not null default now()
);

create index if not exists assets_asset_type_idx on public.assets (asset_type);
create index if not exists assets_created_at_idx on public.assets (created_at desc);

comment on table public.assets is
  'Registry of site asset files uploaded to the assets storage bucket (today: the site logo from SystemSettings). The live logo URL is read from site_settings.site_logo_url; this table is the per-file index of uploads.';

-- ----------------------------------------------------------------------------
-- RLS
-- Restrictive choice (flagged): reads are public because the files live in a
-- PUBLIC bucket (SystemSettings uses getPublicUrl) and the logo is shown to
-- everyone. Writes are super_admin only, matching the code: the only
-- uploader (SystemSettings) sits inside the super_admin-guarded CMS.
-- ----------------------------------------------------------------------------
alter table public.assets enable row level security;

drop policy if exists "assets_select_public" on public.assets;
create policy "assets_select_public"
  on public.assets
  for select
  to anon, authenticated
  using (true);

drop policy if exists "assets_insert_admin" on public.assets;
create policy "assets_insert_admin"
  on public.assets
  for insert
  to authenticated
  with check (public.is_admin());

drop policy if exists "assets_update_admin" on public.assets;
create policy "assets_update_admin"
  on public.assets
  for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "assets_delete_admin" on public.assets;
create policy "assets_delete_admin"
  on public.assets
  for delete
  to authenticated
  using (public.is_admin());

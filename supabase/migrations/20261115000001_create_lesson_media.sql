-- 20261115000001_create_lesson_media.sql
-- Creates public.lesson_media (table) + RLS policies.
--
-- WHY: Backend verification (2026-11-15) found this table missing
-- (PostgREST PGRST205) while every other table the code references exists.
--
-- WHAT THE CODE ACTUALLY DOES TODAY (read before judging this schema):
--   * src/components/admin/SlideBuilder.tsx uploads image/audio files to the
--     STORAGE bucket named 'lesson_media' (which already exists) and stores
--     the resulting public URLs directly on lesson_slides
--     (lesson_slides.media_url / .audio_url, or inside lesson_slides.options
--     JSON for 4-panel slides). NO code in the repo reads or writes a
--     lesson_media TABLE yet.
--   * This table is therefore a media registry that mirrors those uploads:
--     one row per uploaded file, so uploads can be listed, audited and
--     cleaned up later. Creating it closes the verified missing-object gap
--     and changes nothing in the app's current behaviour.
--   * Column choices below are inferred from SlideBuilder.tsx and from the
--     conventions of the sibling tables (downloads / videos / games all use
--     id + title/description + file_url-style columns + created_at). Every
--     inference is marked "-- inferred".
--
-- This file also creates public.is_admin(), a SECURITY DEFINER helper used
-- by the RLS policies here and in 20261115000004_super_admin_rls.sql. It is
-- CREATE OR REPLACE, so re-running is safe.
-- ============================================================================

-- Helper: is the signed-in user a super_admin?
-- SECURITY DEFINER so the lookup on user_profiles bypasses that table's own
-- RLS (avoids policy recursion when used inside user_profiles policies).
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.user_profiles
    where id = auth.uid()
      and role = 'super_admin'
  );
$$;

comment on function public.is_admin() is
  'True when the current auth user has role super_admin in user_profiles. SECURITY DEFINER to avoid RLS recursion.';

-- ----------------------------------------------------------------------------
-- Table
-- ----------------------------------------------------------------------------
create table if not exists public.lesson_media (
  id          uuid primary key default gen_random_uuid(),
  -- The lesson that was selected in SlideBuilder when the file was uploaded.
  lesson_id   uuid references public.curriculum_lessons (id) on delete cascade,
  -- The slide the file ended up on. Nullable: SlideBuilder uploads the file
  -- BEFORE the slide row is saved, so a registry row can exist first.
  slide_id    uuid references public.lesson_slides (id) on delete set null,
  -- Storage object name inside the 'lesson_media' bucket, generated by
  -- SlideBuilder.uploadFile() as: img_<ts>_<rand>.<ext> / aud_<ts>_<rand>.<ext>
  file_name   text not null,
  -- Public URL returned by storage getPublicUrl(); the same value the code
  -- stores on lesson_slides.media_url / audio_url.
  file_url    text not null,
  -- SlideBuilder only ever picks images or audio (pickImage / pickAudio).
  media_type  text not null check (media_type in ('image', 'audio')),
  -- file.mimeType as reported by expo-document-picker (native uploads). -- inferred
  mime_type   text,
  uploaded_by uuid references auth.users (id) on delete set null,
  created_at  timestamptz not null default now()
);

create index if not exists lesson_media_lesson_id_idx on public.lesson_media (lesson_id);
create index if not exists lesson_media_slide_id_idx  on public.lesson_media (slide_id);
create index if not exists lesson_media_media_type_idx on public.lesson_media (media_type);

comment on table public.lesson_media is
  'Registry of image/audio files uploaded to the lesson_media storage bucket via SlideBuilder. The app currently stores media URLs on lesson_slides; this table is the per-file index of the same uploads.';

-- ----------------------------------------------------------------------------
-- RLS
-- Restrictive choice (flagged): reads are public because the files themselves
-- live in a PUBLIC bucket (SlideBuilder uses getPublicUrl) and a future
-- lesson renderer will need to read this table as a learner/anon. Writes are
-- super_admin only, matching the code: the only uploader (SlideBuilder) sits
-- inside the super_admin-guarded CMS.
-- ----------------------------------------------------------------------------
alter table public.lesson_media enable row level security;

drop policy if exists "lesson_media_select_public" on public.lesson_media;
create policy "lesson_media_select_public"
  on public.lesson_media
  for select
  to anon, authenticated
  using (true);

drop policy if exists "lesson_media_insert_admin" on public.lesson_media;
create policy "lesson_media_insert_admin"
  on public.lesson_media
  for insert
  to authenticated
  with check (public.is_admin());

drop policy if exists "lesson_media_update_admin" on public.lesson_media;
create policy "lesson_media_update_admin"
  on public.lesson_media
  for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "lesson_media_delete_admin" on public.lesson_media;
create policy "lesson_media_delete_admin"
  on public.lesson_media
  for delete
  to authenticated
  using (public.is_admin());
